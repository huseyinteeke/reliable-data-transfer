#!/usr/bin/env python3
"""Runs the experiments of PDF section 3.2 and stores everything needed to
reproduce and analyse each run under logs/<exp>/<run>/ :

    scenario.conf  emulator scenario actually used (incl. seed)
    sender.log receiver.log emulator.log
    meta.json      parameters, command lines, exit codes, SHA-256 of input/output
    out.bin        received file (kept only when it differs from the input)

Usage:  python3 scripts/run_experiments.py [--exp 1 2 3 4 5] [--jobs 4]
                                           [--seeds 1 2 3] [--force] [--list]
Each run uses its own UDP ports, so runs can execute in parallel.
"""
import argparse, hashlib, json, os, signal, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "testdata" / "input.bin"
BASELINE = dict(
    rate_fwd_bps=1000000, rate_rev_bps=1000000, queue_fwd_pkts=128, queue_rev_pkts=128,
    delay_fwd_ms=20, delay_rev_ms=20, jitter_ms=0, data_loss=0.0, ack_loss=0.0,
    corrupt=0.0, duplicate=0.0, reorder=0.0)
BASE_PROTO = dict(mode="sr", W=16, k=7, payload=1024)


def run(mode, W, k=7, sc=None, actions=(), extra=(), seeds=(1,), tag=None):
    """One logical run (expanded per seed)."""
    return dict(mode=mode, W=W, k=k, sc=sc or {}, actions=list(actions),
                extra=list(extra), seeds=seeds, tag=tag)


def experiments(seeds):
    ex = {}
    # ---- Experiment 1: ideal network
    r = [run("sw", 1)]
    for W in (1, 2, 4, 8, 16, 32):
        r += [run("gbn", W), run("sr", W)]
    ex[1] = r

    # ---- Experiment 2: data packet loss
    ex[2] = [run(m, 1 if m == "sw" else 16, sc=dict(data_loss=p), seeds=seeds)
             for m in ("sw", "gbn", "sr") for p in (0.0, 0.05, 0.10)]

    # ---- Experiment 3: propagation delay (jitter = 10 % of delay)
    r = []
    for d in (20, 50, 100, 200):
        sc = dict(delay_fwd_ms=d, delay_rev_ms=d, jitter_ms=d * 0.1)
        r.append(run("sw", 1, sc=sc, seeds=seeds))
        for W in (16, 64):
            r.append(run("sr", W, sc=sc, seeds=seeds))
    ex[3] = r

    # ---- Experiment 4: corruption, reordering, duplication, ACK loss
    r = []
    for imp in ("corrupt", "reorder", "duplicate", "ack_loss"):
        for m in ("sw", "gbn", "sr"):
            r.append(run(m, 1 if m == "sw" else 16, sc={imp: 0.05}, seeds=seeds,
                         tag=imp))
    ex[4] = r

    # ---- Experiment 5: sequence-number limits (deterministic per-packet actions)
    # GBN: the first ACKs numbered 1..M-1 are dropped. With W = M the only ACK
    #      that survives for a full window is ACK 0 (= M mod M), which the
    #      sender cannot tell from a duplicate ACK; the receiver then accepts
    #      the retransmitted packet 0 as new data.
    # SR : the first ACK numbered 0 is dropped. With W > M/2 the retransmitted
    #      packet 0 falls inside the receiver's new window and is accepted as
    #      new data instead of being recognised as an old duplicate.
    r = []
    fast = ["--max-retx", "5", "--rto-max", "1000"]
    for k in (3, 4):
        M = 1 << k
        for W in range(1, M + 1):
            r.append(run("gbn", W, k=k, extra=fast + ["--unsafe"],
                         actions=[("drop", "ack", n) for n in range(1, M)],
                         tag=f"gbn_k{k}"))
            r.append(run("sr", W, k=k, extra=fast + ["--unsafe"],
                         actions=[("drop", "ack", 0)], tag=f"sr_k{k}"))
    ex[5] = r
    return ex


def expand(exp_id, runs):
    specs = []
    for r in runs:
        for seed in r["seeds"]:
            sc = dict(BASELINE, **r["sc"])
            parts = [r["mode"], f"W{r['W']}", f"k{r['k']}"]
            if r["tag"]:
                parts.insert(0, r["tag"])
            for key, v in sorted(r["sc"].items()):
                parts.append(f"{key}={v:g}")
            if len(r["seeds"]) > 1 or seed != 1:
                parts.append(f"seed{seed}")
            specs.append(dict(exp=exp_id, name="_".join(parts), seed=seed, mode=r["mode"],
                              W=r["W"], k=r["k"], payload=BASE_PROTO["payload"], sc=sc,
                              actions=r["actions"], extra=r["extra"], tag=r["tag"]))
    return specs


def write_scenario(path, spec):
    lines = [f"# generated by run_experiments.py (exp {spec['exp']}, {spec['name']})"]
    lines += [f"{k} = {v}" for k, v in spec["sc"].items()]
    lines.append(f"seed = {spec['seed']}")
    for a in spec["actions"]:
        lines.append("action " + " ".join(str(x) for x in a))
    path.write_text("\n".join(lines) + "\n")


def sha256(p):
    h = hashlib.sha256()
    try:
        h.update(Path(p).read_bytes())
    except FileNotFoundError:
        return None
    return h.hexdigest()


def execute(spec, bindir, outroot, port, force):
    d = outroot / f"exp{spec['exp']}" / spec["name"]
    if (d / "meta.json").exists() and not force:
        return spec["name"], "cached"
    d.mkdir(parents=True, exist_ok=True)
    write_scenario(d / "scenario.conf", spec)
    out = d / "out.bin"
    if out.exists():
        out.unlink()
    lp, rp = port, port + 1
    emu = [str(bindir / "emulator"), "--listen-port", str(lp), "--dst-port", str(rp),
           "--scenario", str(d / "scenario.conf"), "--log", str(d / "emulator.log")]
    rcv = [str(bindir / "receiver"), "--port", str(rp), "--out", str(out), "--mode",
           spec["mode"], "--window", str(spec["W"]), "--k", str(spec["k"]),
           "--log", str(d / "receiver.log"), "--linger", "1500"]
    snd = [str(bindir / "sender"), "--file", str(INPUT), "--port", str(lp), "--mode",
           spec["mode"], "--window", str(spec["W"]), "--k", str(spec["k"]),
           "--payload", str(spec["payload"]), "--log", str(d / "sender.log")] + spec["extra"]

    t0 = time.time()
    devnull = subprocess.DEVNULL
    pe = subprocess.Popen(emu, stdout=devnull, stderr=devnull)
    pr = subprocess.Popen(rcv, stdout=devnull, stderr=subprocess.PIPE)
    time.sleep(0.2)
    try:
        ps = subprocess.run(snd, capture_output=True, text=True, timeout=900)
        s_rc, s_err = ps.returncode, ps.stderr.strip()
    except subprocess.TimeoutExpired:
        s_rc, s_err = -1, "sender timeout"
    try:
        pr.wait(timeout=4)
    except subprocess.TimeoutExpired:
        pr.send_signal(signal.SIGTERM)
        pr.wait()
    r_err = pr.stderr.read().decode().strip()
    pe.send_signal(signal.SIGTERM)
    pe.wait()

    sha_in, sha_out = sha256(INPUT), sha256(out)
    match = sha_in == sha_out
    meta = dict(exp=spec["exp"], name=spec["name"], tag=spec["tag"], mode=spec["mode"],
                W=spec["W"], k=spec["k"], payload=spec["payload"], seed=spec["seed"],
                scenario=spec["sc"], actions=spec["actions"], sender_extra=spec["extra"],
                sender_cmd=snd, receiver_cmd=rcv, emulator_cmd=emu,
                sender_rc=s_rc, receiver_rc=pr.returncode, sender_stderr=s_err,
                receiver_stderr=r_err, file_size=INPUT.stat().st_size,
                sha_in=sha_in, sha_out=sha_out, match=match,
                wall_s=round(time.time() - t0, 3))
    (d / "meta.json").write_text(json.dumps(meta, indent=1))
    if match and out.exists():
        out.unlink()
    return spec["name"], ("OK" if match else "HASH MISMATCH") + f" ({meta['wall_s']}s)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", type=int, nargs="*", default=[1, 2, 3, 4, 5])
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--seeds", type=int, nargs="*", default=[1, 2, 3],
                    help="seeds for the random experiments (2, 3, 4)")
    ap.add_argument("--force", action="store_true", help="re-run cached runs")
    ap.add_argument("--list", action="store_true", help="only list the runs")
    ap.add_argument("--bin-dir", default=None)
    ap.add_argument("--out", default=str(ROOT / "logs"))
    ap.add_argument("--base-port", type=int, default=20000)
    a = ap.parse_args()

    bindir = Path(a.bin_dir) if a.bin_dir else next(
        (p for p in (ROOT / "build/release/bin", ROOT / "build/debug/bin") if p.exists()), None)
    if bindir is None:
        sys.exit("no build found: cmake --preset release && cmake --build build/release")
    ex = experiments(tuple(a.seeds))
    specs = [s for e in a.exp for s in expand(e, ex[e])]
    if a.list:
        for s in specs:
            print(f"exp{s['exp']}/{s['name']}")
        print(len(specs), "runs")
        return
    outroot = Path(a.out)
    print(f"{len(specs)} runs, binaries {bindir}, {a.jobs} parallel")
    ok = bad = 0
    with ThreadPoolExecutor(max_workers=a.jobs) as pool:
        futs = [(s, pool.submit(execute, s, bindir, outroot, a.base_port + 2 * i, a.force))
                for i, s in enumerate(specs)]
        for s, f in futs:
            name, res = f.result()
            print(f"exp{s['exp']}/{name}: {res}", flush=True)
            if res.startswith("HASH"):
                bad += 1
            else:
                ok += 1
    print(f"done: {ok} matched/cached, {bad} hash mismatches "
          "(mismatches are expected only in experiment 5)")


if __name__ == "__main__":
    main()
